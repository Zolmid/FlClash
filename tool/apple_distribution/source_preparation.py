#!/usr/bin/env python3
"""Reusable iOS source preparation and unsigned-archive manual signing helpers."""

from __future__ import annotations

import json
import plistlib
import shutil
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Mapping, Optional

from apple_distribution import (
    APP_GROUP,
    NETWORK_EXTENSION,
    RENEWAL_KEYCHAIN_GROUP,
    TARGET_APPEX_NAMES,
    TARGET_BUNDLE_IDS,
    TEAM_ID,
    Profile,
    Runner,
    ValidationError,
    absolute_path,
    run_argv,
    safe_text,
    validate_app_renewal_contract,
    validate_archive_bundle,
)

DISTRIBUTION_TO_NATIVE = {
    'release-testing': 'direct',
    'app-store-connect': 'apple-app-store',
}


def native_distribution_for(distribution: str) -> str:
    if distribution not in DISTRIBUTION_TO_NATIVE:
        raise ValidationError('distribution must be release-testing or app-store-connect')
    return DISTRIBUTION_TO_NATIVE[distribution]


def _ensure_entitlements_keychain_group(path: Path, group_expr: str) -> None:
    if not path.is_file() or path.is_symlink():
        raise ValidationError(f'missing entitlements file {path}')
    tree = ET.parse(path)
    root = tree.getroot()
    plist_dict = root.find('dict')
    if plist_dict is None:
        raise ValidationError(f'entitlements plist missing root dict in {path}')
    children = list(plist_dict)
    kc_array: Optional[ET.Element] = None
    for idx, child in enumerate(children):
        if child.tag == 'key' and (child.text or '').strip() == 'keychain-access-groups':
            if idx + 1 >= len(children) or children[idx + 1].tag != 'array':
                raise ValidationError(f'malformed keychain-access-groups in {path}')
            kc_array = children[idx + 1]
            break
    if kc_array is None:
        key_el = ET.Element('key')
        key_el.text = 'keychain-access-groups'
        kc_array = ET.Element('array')
        plist_dict.insert(0, kc_array)
        plist_dict.insert(0, key_el)
    existing = [(item.text or '').strip() for item in kc_array.findall('string')]
    if group_expr not in existing:
        str_el = ET.SubElement(kc_array, 'string')
        str_el.text = group_expr
    xml_body = ET.tostring(root, encoding='utf-8').decode('utf-8')
    header = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n'
    )
    path.write_text(header + xml_body + '\n', encoding='utf-8')


def _ensure_info_plist_renewal_fields(path: Path) -> None:
    if not path.is_file() or path.is_symlink():
        raise ValidationError(f'missing Info.plist at {path}')
    with path.open('rb') as stream:
        payload = plistlib.load(stream)
    if not isinstance(payload, dict):
        raise ValidationError(f'invalid Info.plist dictionary in {path}')
    payload['ZolNitRenewalKeychainAccessGroup'] = '$(ZOLNIT_RENEWAL_KEYCHAIN_GROUP)'
    payload['ZolNitDistribution'] = '$(ZOLNIT_NATIVE_DISTRIBUTION)'
    payload['ZolNitRenewalWhileLocked'] = True
    with path.open('wb') as stream:
        plistlib.dump(payload, stream, sort_keys=False)


def prepare_ios_source_tree(
    source_repo: Path,
    distribution: str,
    *,
    app_bundle_id: str = TARGET_BUNDLE_IDS['app'],
    team_id: str = TEAM_ID,
    renewal_keychain_group: str = RENEWAL_KEYCHAIN_GROUP,
) -> dict[str, str]:
    if not source_repo.is_dir() or source_repo.is_symlink():
        raise ValidationError('source_repo must be an existing directory')
    safe_text(app_bundle_id, 'app bundle ID')
    if team_id != TEAM_ID:
        raise ValidationError('Team ID mismatch')
    if renewal_keychain_group != RENEWAL_KEYCHAIN_GROUP:
        raise ValidationError('renewal keychain group mismatch')
    native_dist = native_distribution_for(distribution)
    env_data = {
        'APP_ENV': 'stable',
        'ZOLNIT_DISTRIBUTION': native_dist,
        'ZOLNIT_NATIVE_UI': 'true',
        'ZOLNIT_CLIENT_BUNDLE': 'true',
    }
    (source_repo / 'env.json').write_text(json.dumps(env_data), encoding='utf-8')
    xcconfig_path = source_repo / 'ios' / 'Flutter' / 'GeneratedBundleConfig.xcconfig'
    xcconfig_path.parent.mkdir(parents=True, exist_ok=True)
    xcconfig_path.write_text(
        '// Generated by source_preparation.py. Do not edit.\n'
        f'APP_BUNDLE_ID = {app_bundle_id}\n'
        f'ZOLNIT_NATIVE_DISTRIBUTION = {native_dist}\n'
        f'ZOLNIT_RENEWAL_KEYCHAIN_GROUP = {renewal_keychain_group}\n',
        encoding='utf-8',
    )
    _ensure_entitlements_keychain_group(
        source_repo / 'ios' / 'Runner' / 'Runner.entitlements',
        '$(ZOLNIT_RENEWAL_KEYCHAIN_GROUP)',
    )
    _ensure_entitlements_keychain_group(
        source_repo / 'ios' / 'NECore' / 'NECore.entitlements',
        '$(ZOLNIT_RENEWAL_KEYCHAIN_GROUP)',
    )
    _ensure_info_plist_renewal_fields(source_repo / 'ios' / 'Runner' / 'Info.plist')
    _ensure_info_plist_renewal_fields(source_repo / 'ios' / 'NECore' / 'Info.plist')
    return {
        'distribution': distribution,
        'native_distribution': native_dist,
        'app_bundle_id': app_bundle_id,
        'team_id': team_id,
        'renewal_keychain_group': renewal_keychain_group,
    }


def unsigned_archive_command(
    workspace_path: Path,
    archive_path: Path,
    derived_data_path: Optional[Path] = None,
) -> list[str]:
    cmd = [
        'xcodebuild', 'archive',
        '-workspace', str(workspace_path),
        '-scheme', 'Runner',
        '-configuration', 'Release',
        '-sdk', 'iphoneos',
        '-destination', 'generic/platform=iOS',
        '-archivePath', str(archive_path),
    ]
    if derived_data_path is not None:
        cmd.extend(['-derivedDataPath', str(derived_data_path)])
    cmd.extend([
        'CODE_SIGNING_ALLOWED=NO',
        'CODE_SIGNING_REQUIRED=NO',
        'CODE_SIGN_IDENTITY=',
        'DEVELOPMENT_TEAM=',
    ])
    return cmd


def projected_target_entitlements(target: str, distribution: str) -> dict[str, object]:
    if target not in TARGET_BUNDLE_IDS:
        raise ValidationError(f'unknown target {target}')
    native_distribution_for(distribution)
    bundle_id = TARGET_BUNDLE_IDS[target]
    ent: dict[str, object] = {
        'application-identifier': f'{TEAM_ID}.{bundle_id}',
        'com.apple.developer.team-identifier': TEAM_ID,
        'com.apple.security.application-groups': [APP_GROUP],
        'com.apple.developer.networking.networkextension': [NETWORK_EXTENSION],
        'get-task-allow': False,
    }
    if target == 'app':
        ent['com.apple.developer.networking.wifi-info'] = True
        ent['keychain-access-groups'] = [f'{TEAM_ID}.{bundle_id}', RENEWAL_KEYCHAIN_GROUP]
        if distribution == 'app-store-connect':
            ent['beta-reports-active'] = True
    elif target == 'necore':
        ent['keychain-access-groups'] = [RENEWAL_KEYCHAIN_GROUP]
    return ent


def sign_archive_bundle(
    archive_path: Path,
    distribution: str,
    profiles: Mapping[str, Profile],
    signing_identity: str,
    runner: Runner = run_argv,
    *,
    keychain_path: Optional[Path] = None,
) -> list[list[str]]:
    safe_text(signing_identity, 'signing identity')
    if set(profiles) != set(TARGET_BUNDLE_IDS):
        raise ValidationError('all three target profiles are required to sign archive')
    validate_archive_bundle(archive_path)
    app_dir = archive_path / 'Products' / 'Applications' / 'Runner.app'
    necore_dir = app_dir / 'PlugIns' / TARGET_APPEX_NAMES['necore']
    widget_dir = app_dir / 'PlugIns' / TARGET_APPEX_NAMES['widget']
    if not widget_dir.is_dir() or widget_dir.is_symlink():
        raise ValidationError('missing PlugIns/Widget.appex bundle in archive')
    kc_args = ['--keychain', str(keychain_path)] if keychain_path is not None else []
    executed: list[list[str]] = []
    frameworks_dir = app_dir / 'Frameworks'
    if frameworks_dir.is_dir():
        for item in sorted(frameworks_dir.iterdir()):
            if item.suffix in {'.framework', '.dylib'}:
                cmd = ['codesign', '--force', '--sign', signing_identity, '--timestamp=none', *kc_args, str(item)]
                res = runner(cmd)
                if res.returncode != 0:
                    raise ValidationError(f'failed to sign embedded framework {item.name}')
                executed.append(cmd)
    with tempfile.TemporaryDirectory(prefix='zolnit-ent-') as temp_name:
        temp_dir = Path(temp_name)
        for target, bundle_dir in (('necore', necore_dir), ('widget', widget_dir), ('app', app_dir)):
            embedded = bundle_dir / 'embedded.mobileprovision'
            shutil.copyfile(profiles[target].path, embedded)
            ent_path = temp_dir / f'{target}.entitlements'
            with ent_path.open('wb') as stream:
                plistlib.dump(projected_target_entitlements(target, distribution), stream)
            cmd = [
                'codesign', '--force', '--sign', signing_identity,
                '--timestamp=none', '--entitlements', str(ent_path),
                *kc_args, str(bundle_dir),
            ]
            res = runner(cmd)
            if res.returncode != 0:
                raise ValidationError(f'failed to sign archive target {target}')
            executed.append(cmd)
    verify_cmd = ['codesign', '--verify', '--deep', '--strict', '--verbose=2', str(app_dir)]
    verify_res = runner(verify_cmd)
    if verify_res.returncode != 0:
        raise ValidationError('signed archive failed codesign verification')
    executed.append(verify_cmd)
    validate_app_renewal_contract(app_dir, runner, check_signed_entitlements=True)
    return executed
